CREATE TABLE cobros (
    id_cobro UUID PRIMARY KEY,
    id_envio UUID NOT NULL,
    monto NUMERIC(12, 2) NOT NULL,
    moneda VARCHAR(3) NOT NULL,
    medio_pago VARCHAR(20) NOT NULL,
    referencia_operacion VARCHAR(100),
    estado_pago VARCHAR(20) NOT NULL,
    fecha_hora TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_cobro_envio_referencia UNIQUE (id_envio, referencia_operacion)
);

CREATE TABLE guias (
    id_guia UUID PRIMARY KEY,
    id_envio UUID NOT NULL,
    id_cobro UUID NOT NULL,
    codigo_guia VARCHAR(18) NOT NULL,
    url_seguimiento VARCHAR(500) NOT NULL,
    fecha_emision TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_guia_envio UNIQUE (id_envio),
    CONSTRAINT uk_guia_codigo UNIQUE (codigo_guia)
);

CREATE TABLE notificaciones (
    notificacion_id UUID PRIMARY KEY,
    cliente_id UUID NOT NULL,
    envio_id UUID,
    tipo VARCHAR(40) NOT NULL,
    canal VARCHAR(30) NOT NULL,
    mensaje VARCHAR(255) NOT NULL,
    campos_invalidos VARCHAR(1638),
    motivo VARCHAR(200),
    fecha_envio TIMESTAMP WITH TIME ZONE NOT NULL,
    estado VARCHAR(30) NOT NULL,
    numero_intentos INTEGER NOT NULL
);

CREATE TABLE notificacion_intentos (
    intento_id UUID PRIMARY KEY,
    notificacion_id UUID NOT NULL,
    numero_intento INTEGER NOT NULL,
    fecha_intento TIMESTAMP WITH TIME ZONE NOT NULL,
    resultado VARCHAR(30) NOT NULL,
    detalle VARCHAR(200)
);
