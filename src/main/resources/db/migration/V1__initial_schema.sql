CREATE TABLE clientes (
    id_cliente UUID PRIMARY KEY,
    tipo_documento VARCHAR(20) NOT NULL,
    numero_documento VARCHAR(50) NOT NULL,
    nombres VARCHAR(150) NOT NULL,
    direccion VARCHAR(250) NOT NULL,
    telefono VARCHAR(30),
    correo VARCHAR(254),
    rol VARCHAR(20) NOT NULL,
    CONSTRAINT uk_cliente_documento UNIQUE (tipo_documento, numero_documento)
);

CREATE TABLE envios (
    id_envio UUID PRIMARY KEY,
    id_remitente VARCHAR(50),
    id_destinatario VARCHAR(50),
    peso_kg NUMERIC(10, 3),
    contenido VARCHAR(500),
    linea_negocio VARCHAR(80),
    origen VARCHAR(150),
    destino VARCHAR(150),
    estado VARCHAR(30) NOT NULL,
    servicio VARCHAR(30),
    zona VARCHAR(30),
    ida_vuelta BOOLEAN,
    tarifa_total NUMERIC(12, 2),
    simulacion_log VARCHAR(1000),
    CONSTRAINT uk_envio_datos UNIQUE
        (id_remitente, id_destinatario, peso_kg, contenido, linea_negocio, origen, destino)
);

CREATE TABLE contenidos_prohibidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria VARCHAR(100) NOT NULL,
    palabra_clave VARCHAR(150) NOT NULL,
    activo BOOLEAN NOT NULL
);

